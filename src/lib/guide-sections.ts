export const ALL_GUIDE_SECTIONS: GuideSection[] = [...CLIENT_GUIDE, ...ADMIN_GUIDE]

const GUIDE_IDS = new Set(ALL_GUIDE_SECTIONS.map((s) => s.id))

/** True when a HelpLink anchor points at a real section (guards silent rot). */
export function hasGuideAnchor(id: string): boolean {
  return GUIDE_IDS.has(id)
}

export function sectionsFor(kind: 'client' | 'admin'): GuideSection[] {
  return kind === 'admin' ? ADMIN_GUIDE : CLIENT_GUIDE
}
